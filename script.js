let currentUser = JSON.parse(localStorage.getItem('current_user')) || null;

document.addEventListener('DOMContentLoaded', () => {
    const coursesContainer = document.getElementById('courses-container');

    courses.forEach((course, index) => {
        const card = document.createElement('div');
        card.className = 'course-card reveal';
        card.style.transitionDelay = `${index * 0.1}s`;
        card.innerHTML = `
            <img src="${course.img}" alt="${course.title}" class="course-img">
            <div class="course-info">
                <span class="course-badge">${course.category}</span>
                <h3>${course.title}</h3>
                <p>${course.desc}</p>
                <div class="course-meta">
                    <span class="course-price">${course.price}</span>
                    <button class="btn btn-primary learn-btn" data-title="${course.title}">למד עכשיו</button>
                </div>
            </div>
        `;
        coursesContainer.appendChild(card);
    });

    // Intersection Observer
    const revealCallback = (entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('active');
            }
        });
    };
    const observer = new IntersectionObserver(revealCallback, { threshold: 0.1 });
    document.querySelectorAll('.reveal').forEach(el => observer.observe(el));

    // Sticky Header
    window.addEventListener('scroll', () => {
        const header = document.getElementById('header');
        if (header && window.scrollY > 50) {
            header.classList.add('scrolled');
        } else if (header) {
            header.classList.remove('scrolled');
        }
    });

    // Typing Animation
    const typingSpan = document.getElementById('typing-text');
    if (typingSpan) {
        const words = ["AI", "בינה מלאכותית", "העתיד", "טכנולוגיה חכמה"];
        let wordIndex = 0, charIndex = 0, isDeleting = false, typeSpeed = 200;
        function type() {
            const currentWord = words[wordIndex];
            const displayedText = isDeleting ? currentWord.substring(0, charIndex - 1) : currentWord.substring(0, charIndex + 1);
            typingSpan.textContent = displayedText;
            if (!isDeleting && charIndex === currentWord.length) { isDeleting = true; typeSpeed = 1500; }
            else if (isDeleting && charIndex === 0) { isDeleting = false; wordIndex = (wordIndex + 1) % words.length; typeSpeed = 500; }
            else { typeSpeed = isDeleting ? 100 : 200; charIndex = isDeleting ? charIndex - 1 : charIndex + 1; }
            setTimeout(type, typeSpeed);
        }
        type();
    }

    // Particles
    const particleContainer = document.getElementById('particles-js');
    if (particleContainer) {
        for (let i = 0; i < 50; i++) {
            const p = document.createElement('div');
            p.className = 'particle';
            p.style.left = Math.random() * 100 + '%';
            p.style.top = Math.random() * 100 + '%';
            p.style.width = p.style.height = Math.random() * 3 + 'px';
            p.style.background = 'white'; p.style.position = 'absolute'; p.style.borderRadius = '50%'; p.style.opacity = Math.random();
            p.style.animation = `twinkle ${Math.random() * 5 + 2}s infinite alternate`;
            particleContainer.appendChild(p);
        }
    }
    const style = document.createElement('style');
    style.innerHTML = `@keyframes twinkle { from { opacity: 0.2; transform: scale(1); } to { opacity: 1; transform: scale(1.5); } }`;
    document.head.appendChild(style);

    // Auth UI
    const userWelcome = document.getElementById('user-welcome');
    const authContainer = document.getElementById('auth-container');
    function updateUIForLogin(name) {
        userWelcome.textContent = `ברוך הבא, ${name}!`;
        userWelcome.style.display = 'block';
        authContainer.querySelectorAll('.btn').forEach(btn => btn.style.display = 'none');
    }
    if (currentUser) updateUIForLogin(currentUser.name);

    // Course Viewer Logic
    function openCourseViewer(courseTitle) {
        const course = courses.find(c => c.title === courseTitle);
        if (!course) return;
        const viewerContent = document.getElementById('course-details-content');
        viewerContent.innerHTML = `
            <div id="course-overview-view">
                <img src="${course.img}" class="course-full-img" alt="${course.title}">
                <span class="content-badge">${course.category} | ${course.fullContent.level}</span>
                <h2>${course.title}</h2>
                <div class="course-full-description">${course.fullContent.description}</div>
                
                <h3>סילבוס הקורס (לחץ על שיעור כדי להתחיל)</h3>
                <div class="syllabus-list">
                    ${course.fullContent.syllabus.map((item, i) => `
                        <div class="syllabus-item" onclick="viewLesson('${course.title}', ${i})">
                            <div class="syllabus-item-number">${i + 1}</div>
                            <div class="syllabus-item-text">${item}</div>
                        </div>
                    `).join('')}
                </div>
                
                <div style="margin-top: 40px; padding: 20px; background: var(--primary-glow); border-radius: 15px; text-align: center;">
                    <h4 style="margin-bottom: 10px;">משך הקורס: ${course.fullContent.duration}</h4>
                    <button class="btn btn-primary" onclick="viewLesson('${course.title}', 0)">התחל שיעור ראשון</button>
                </div>
            </div>
            <div id="lesson-view" style="display: none;">
                <!-- Lesson content will be injected here -->
            </div>
        `;
        toggleModal('course-viewer-modal');
    }

    // Export to global for onclick handlers
    window.viewLesson = function (courseTitle, lessonIndex) {
        const course = courses.find(c => c.title === courseTitle);
        if (!course) return;

        const overview = document.getElementById('course-overview-view');
        const lessonContainer = document.getElementById('lesson-view');

        // Mocking extensive content if not defined
        const lesson = course.fullContent.lessons[lessonIndex] || {
            title: course.fullContent.syllabus[lessonIndex],
            content: `
                <h4>ברוכים הבאים לשיעור ${lessonIndex + 1}</h4>
                <p>שיעור זה עוסק ב: <strong>${course.fullContent.syllabus[lessonIndex]}</strong>.</p>
                <div style="background: rgba(255,255,255,0.05); padding: 30px; border-radius: 15px; margin: 30px 0; border: 1px dashed var(--primary);">
                    <p style="font-size: 1.1rem; color: var(--text-muted);">כאן תמצאו את התכנים המקצועיים, סרטוני הדרכה, קבצי עבודה ומשימות לתרגול.</p>
                    <p>אנחנו עובדים על סרטון ההדרכה הרלוונטי לשיעור זה. בינתיים, מומלץ לעבור על המצגת והחומרים הכתובים.</p>
                </div>
                <h5>משימת השיעור:</h5>
                <p>כתבו סיכום קצר של הנלמד ושלחו בפורום הקורס.</p>
            `
        };

        overview.style.display = 'none';
        lessonContainer.style.display = 'block';

        lessonContainer.innerHTML = `
            <button class="btn btn-outline" style="margin-bottom: 20px; border: 1px solid var(--primary); color: var(--primary); background: none;" onclick="showCourseOverview()">← חזרה לסילבוס</button>
            <span class="content-badge">שיעור ${lessonIndex + 1} מתוך ${course.fullContent.syllabus.length}</span>
            <h2 style="font-size: 2.2rem; margin-bottom: 20px;">${lesson.title}</h2>
            
            <div class="lesson-body glass" style="padding: 30px; border-radius: 20px;">
                ${lesson.content}
            </div>

            <div style="display: flex; justify-content: space-between; margin-top: 40px;">
                ${lessonIndex > 0 ? `<button class="btn btn-primary" onclick="viewLesson('${courseTitle}', ${lessonIndex - 1})">שיעור קודם</button>` : '<div></div>'}
                ${lessonIndex < course.fullContent.syllabus.length - 1 ? `<button class="btn btn-primary" onclick="viewLesson('${courseTitle}', ${lessonIndex + 1})">שיעור הבא</button>` : `<button class="btn btn-primary" style="background: #10b981;" onclick="alert('כל הכבוד! סיימת את הקורס.')">סיים קורס 🎉</button>`}
            </div>
        `;

        // Scroll to top of modal
        document.querySelector('#course-viewer-modal .modal-content').scrollTop = 0;
    };

    window.showCourseOverview = function () {
        document.getElementById('course-overview-view').style.display = 'block';
        document.getElementById('lesson-view').style.display = 'none';
    };

    coursesContainer.addEventListener('click', (e) => {
        if (e.target.classList.contains('learn-btn')) {
            if (!currentUser) {
                alert('יש להירשם או להתחבר כדי לגשת לקורסים!');
                toggleModal('register-modal');
            } else {
                openCourseViewer(e.target.dataset.title);
            }
        }
    });

    const loginForm = document.getElementById('login-form');
    const registerForm = document.getElementById('register-form');
    function handleLoginAction(name, email) {
        currentUser = { name, email };
        localStorage.setItem('current_user', JSON.stringify(currentUser));
        localStorage.setItem('user_' + email, JSON.stringify({ name }));
        updateUIForLogin(name);
        document.querySelectorAll('.modal').forEach(m => m.style.display = 'none');
    }
    if (loginForm) {
        loginForm.addEventListener('submit', (e) => {
            e.preventDefault();
            const email = document.getElementById('login-email').value;
            const storedUser = JSON.parse(localStorage.getItem('user_' + email));
            handleLoginAction(storedUser ? storedUser.name : email.split('@')[0], email);
        });
    }
    if (registerForm) {
        registerForm.addEventListener('submit', (e) => {
            e.preventDefault();
            handleLoginAction(document.getElementById('register-name').value, document.getElementById('register-email').value);
        });
    }

    // Contact Form Integration
    const contactUsForm = document.getElementById('contact-us-form');
    if (contactUsForm) {
        contactUsForm.addEventListener('submit', async (e) => {
            e.preventDefault();
            const submitBtn = contactUsForm.querySelector('button[type="submit"]');
            const originalBtnText = submitBtn.textContent;

            submitBtn.textContent = 'שולח...';
            submitBtn.disabled = true;

            const formData = {
                name: document.getElementById('contact-name').value,
                email: document.getElementById('contact-email').value,
                message: document.getElementById('contact-message').value
            };

            try {
                const response = await fetch('http://localhost:3000/send-email', {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json',
                    },
                    body: JSON.stringify(formData),
                });

                const result = await response.json();

                if (result.success) {
                    alert('תודה! ההודעה נשלחה בהצלחה.');
                    contactUsForm.reset();
                } else {
                    alert('שגיאה בשליחת ההודעה. נסה שוב מאוחר יותר.');
                }
            } catch (error) {
                console.error('Error:', error);
                alert('שגיאה בחיבור לשרת. וודא שהשרת פועל.');
            } finally {
                submitBtn.textContent = originalBtnText;
                submitBtn.disabled = false;
            }
        });
    }
});

function toggleModal(id) {
    const modal = document.getElementById(id);
    if (modal) modal.style.display = modal.style.display === 'flex' ? 'none' : 'flex';
}
window.onclick = function (event) { if (event.target.classList.contains('modal')) event.target.style.display = 'none'; }
